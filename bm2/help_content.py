def _quick_score_text(quick_scores: list[int] | tuple[int, ...] | None) -> str:
    scores = [str(value) for value in (quick_scores or [])]
    if not scores:
        return "页面会按系统配置显示快捷分数按钮，点击后只会填入当前成员这一格。"
    return f"页面当前会显示 {'、'.join(scores)} 这些快捷分数，点击后只会填入当前成员这一格。"


